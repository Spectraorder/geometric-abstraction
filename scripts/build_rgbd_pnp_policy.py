"""Bundle a reusable PnP mechanism with an explicit, separately supplied task adapter."""
import argparse
import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def build(adapter=None, base=None):
    base = ROOT/'policies/pick_place_rgbd_base.py' if base is None else Path(base)
    adapter = ROOT/'policies/stack_from_rgbd_pnp_adapter.py' if adapter is None else Path(adapter)
    source = base.read_text()+'\n\n'+adapter.read_text()
    if not any(isinstance(node, ast.FunctionDef) and node.name=='run' for node in ast.parse(source).body):
        raise ValueError('The adapter must define run(api)')
    return '# Generated by scripts/build_rgbd_pnp_policy.py; edit the base and adapter separately.\n'+source


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--adapter', type=Path)
    parser.add_argument('--base', type=Path, help='Explicit shared primitive source; original extraction remains the default')
    args = parser.parse_args()
    from run_vision_trial import validate_source
    source = build(args.adapter, args.base)
    validate_source(source)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(source)
    print(args.output)
