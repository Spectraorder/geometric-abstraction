"""Bundle CPU numerical helpers and the inventory controller for isolation."""
import argparse
import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODULES = ('gripper_geometry', 'cube_geometry', 'cuboid_geometry',
           'instance_geometry', 'inventory_policy')


def build_policy(controller='inventory_policy', pointing=False, refine=False):
    bodies = []
    if refine and controller != 'cube_alignment_policy':
        raise ValueError('Experimental refinement requires the cube alignment controller')
    if controller not in ('inventory_policy', 'column_policy', 'structure_policy', 'cube_alignment_policy'):
        raise ValueError('Unknown inventory controller')
    helpers = (*MODULES[:-1], 'column_geometry', 'column_tracking') if controller in ('column_policy', 'structure_policy', 'cube_alignment_policy') else MODULES[:-1]
    if controller == 'structure_policy':
        helpers = (*helpers, 'structure_geometry', 'beam_geometry')
    if controller == 'cube_alignment_policy':
        helpers = (*helpers, 'cube_alignment')
    if pointing:
        if controller != 'structure_policy':
            raise ValueError('Pointing requires the structure controller')
        helpers = (*helpers, 'pointing_geometry', 'pointing_recovery')
    for name in (*helpers, controller):
        tree = ast.parse((ROOT / 'src/aspire_so100' / (name + '.py')).read_text())
        for node in tree.body:
            if name == 'pointing_geometry' and not (isinstance(node, ast.FunctionDef) and node.name == 'locate_pointed_component'):
                continue
            if isinstance(node, ast.ImportFrom) and node.module.startswith('aspire_so100'):
                continue
            if isinstance(node, ast.FunctionDef) and node.name == 'color_mask':
                continue
            bodies.append(node)
    bodies.extend(ast.parse('color_mask = inventory_color_mask').body)
    if pointing:
        bodies.extend(ast.parse('run_cpu = run\ndef run(api):\n    return run_cpu(api, pointing=True)').body)
    if refine:
        bodies.extend(ast.parse('run_alignment = run\ndef run(api):\n    return run_alignment(api, refine=True)').body)
    return '# Generated by scripts/build_inventory_policy.py; edit source modules.\n' + ast.unparse(ast.Module(body=bodies, type_ignores=[])) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--controller', choices=('inventory_policy', 'column_policy', 'structure_policy', 'cube_alignment_policy'), default='inventory_policy')
    parser.add_argument('--pointing', action='store_true', help='Opt in to hosted RGB-only pointing recovery')
    parser.add_argument('--refine', action='store_true', help='Opt in to experimental post-release regrasp; not validated for deployment')
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(build_policy(args.controller, pointing=args.pointing, refine=args.refine))
    print(args.output)
